const HS_KEY = 'joe_typestorm_scores';
const USERNAME_KEY = 'joe_typestorm_username';

export function loadHighScores(): HighScore[] {
  try {
    const raw = localStorage.getItem(HS_KEY);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch {
    return [];
  }
}

export function saveHighScore(entry: HighScore): HighScore[] {
  const scores = loadHighScores();
  scores.push(entry);
  scores.sort((a, b) => b.score - a.score);
  const top = scores.slice(0, 20);
  localStorage.setItem(HS_KEY, JSON.stringify(top));
  return top;
}

