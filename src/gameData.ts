export type Difficulty = 'easy' | 'medium' | 'hard' | 'custom';

export function getRandomWord(difficulty: Difficulty): string {
  if (difficulty === 'custom') return ''; // handled by engine
  const pool = WORD_POOLS[difficulty];
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getDifficultyForLevel(level: number): Difficulty {
  if (level <= 3) return 'easy';
  if (level <= 7) return 'medium';
  return 'hard';
}

export function getDifficultyForWord(word: string): Difficulty {
  if (word.length <= 3) return 'easy';
  if (word.length <= 6) return 'medium';
  return 'hard';
}

/**
 * Parse a user sentence/paragraph into an array of unique, lowercase words.
 * Strips punctuation, filters out empty strings and single chars.
 */
export function parseSentenceToWords(sentence: string): string[] {
  const raw = sentence
    .toLowerCase()
    .replace(/[^a-z0-9\s'-]/g, ' ')  // keep letters, numbers, apostrophes, hyphens
    .split(/\s+/)
    .map(w => w.replace(/^['-]+|['-]+$/g, '')) // trim leading/trailing punctuation
    .filter(w => w.length >= 2);  // at least 2 chars

  // deduplicate while preserving order
  const seen = new Set<string>();
  const unique: string[] = [];
  for (const w of raw) {
    if (!seen.has(w)) {
      seen.add(w);
      unique.push(w);
    }
  }
  return unique;
}

